// Walks the studio headlessly: cut pieces from two portraits, move one, melt, download, save, reload, own photo.
const { chromium } = require('playwright');
const fs = require('fs');
const [w, h, name] = [+(process.argv[2] || 1280), +(process.argv[3] || 800), process.argv[4] || 'd'];
const out = process.env.OUT, photo = process.env.PHOTO;
(async () => {
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-webgl', '--ignore-gpu-blocklist', '--enable-unsafe-swiftshader'] });
  const ctx = await b.newContext({ viewport: { width: w, height: h }, acceptDownloads: true, hasTouch: w < 500 });
  const p = await ctx.newPage();
  await p.addInitScript(() => { window.__DEBUG = { speed: 8 }; });
  p.on('console', (m) => { if (m.type() === 'error') console.log('error', m.text().slice(0, 300)); });
  p.on('pageerror', (e) => console.log('PAGEERROR', e.message));
  await p.goto('file://' + process.cwd() + '/dist/index.html#studio');
  await p.waitForFunction(() => window.__store && window.__store.getState().ready, null, { timeout: 200000 });
  await p.waitForTimeout(3500);
  console.log('view', await p.evaluate(() => window.__store.getState().view));
  const cut = async (fx, fy, r) => {
    const box = await p.locator('svg.cut').boundingBox();
    const X = (t) => box.x + box.width * (fx + Math.cos(t) * r), Y = (t) => box.y + box.height * (fy + Math.sin(t) * r * 0.62);
    await p.mouse.move(X(0), Y(0));
    await p.mouse.down();
    for (let i = 1; i <= 24; i++) await p.mouse.move(X((i / 24) * 6.283), Y((i / 24) * 6.283));
    await p.mouse.up();
    await p.waitForTimeout(200);
  };
  await p.locator('svg.cut').scrollIntoViewIfNeeded();
  await p.click('#portrait-3');
  await p.click('#cut-Eyes');
  await p.click('#portrait-6');
  await p.click('#cut-Nose');
  await p.click('#portrait-2');
  await p.click('#cut-Mouth');
  await p.click('#portrait-5');
  await p.click('#cut-Brows');
  await p.click('#portrait-4');
  await cut(0.5, 0.86, 0.13);         // by hand
  console.log('layers', await p.locator('.layers li').allTextContents());
  await p.fill('#studio-size', '105');
  await p.fill('#studio-turn', '-2');
  await p.locator('#studio-canvas').scrollIntoViewIfNeeded();
  await p.waitForTimeout(400);
  await p.screenshot({ path: `${out}/${name}-pieces.png`, timeout: 60000 });
  const t0 = Date.now();
  await p.click('#studio-blend');
  await p.waitForSelector('#studio-toggle', { timeout: 120000 });
  console.log('melt ms', Date.now() - t0, 'status', JSON.stringify(await p.textContent('#studio-status')));
  await p.waitForTimeout(400);
  await p.screenshot({ path: `${out}/${name}-melted.png`, timeout: 60000 });
  const [dl] = await Promise.all([p.waitForEvent('download', { timeout: 60000 }), p.click('#studio-download')]);
  await dl.saveAs(`${out}/${name}-face.png`);
  console.log('downloaded', dl.suggestedFilename(), fs.statSync(`${out}/${name}-face.png`).size);
  await p.fill('#studio-name', 'Test face');
  await p.click('#studio-save');
  console.log('save', JSON.stringify(await p.textContent('#studio-status')));
  await p.click('#studio-toggle');
  await p.reload();
  await p.waitForFunction(() => window.__store && window.__store.getState().ready, null, { timeout: 200000 });
  await p.waitForTimeout(2500);
  await p.click('.works li button');
  await p.waitForTimeout(300);
  console.log('after reload layers', await p.locator('.layers li').count());
  const [dl2] = await Promise.all([p.waitForEvent('download', { timeout: 60000 }), p.click('#studio-share')]);
  console.log('share fell back', dl2.suggestedFilename(), JSON.stringify(await p.textContent('#studio-status')));
  await dl2.saveAs(`${out}/${name}-pieces-flat.png`);
  await p.setInputFiles('#studio-photo', photo);
  await p.waitForSelector('#studio-tap', { timeout: 20000 });
  const box = await p.locator('svg.cut').boundingBox();
  for (const [fx, fy] of [[0.405, 0.455], [0.63, 0.455], [0.518, 0.71]]) {
    console.log(await p.textContent('#studio-tap'));
    await p.mouse.click(box.x + box.width * fx, box.y + box.height * fy);
    await p.waitForTimeout(250);
  }
  await p.waitForTimeout(800);
  console.log('thumbs', await p.locator('.thumbs button').count());
  await p.screenshot({ path: `${out}/${name}-own.png`, timeout: 60000 });
  await cut(0.5, 0.5, 0.2);
  await p.click('#studio-save');
  console.log('save with own', JSON.stringify(await p.textContent('#studio-status')));
  console.log('stored mentions own photo', await p.evaluate(() => (localStorage.getItem('collective-face.studio.v1') || '').includes('own-') ));
  await p.evaluate(() => window.__store.getState().go('family'));
  await p.waitForTimeout(1200);
  console.log('back to family, frames run', await p.evaluate(() => window.__three.frameloop));
  await b.close();
})().catch((e) => { console.log('FAILED', e.message.slice(0, 400)); process.exit(1); });
